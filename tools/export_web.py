"""Export verified exercises to website/data/exercises.js (+ original ad-page images)."""
import json, glob, os
import pymupdf as fitz, sys
sys.path.insert(0, "tools")
from ad_styles import style_for, icon_for
s = json.load(open("extraction/audit_stats.json"))
dupof = {d: k for k, v in s["dup_groups"].items() for d in v}
papers = [json.load(open(f)) for f in sorted(glob.glob("extraction/papers/P??.json"))]
d = fitz.open("source/original.pdf")
os.makedirs("website/data", exist_ok=True); os.makedirs("website/img", exist_ok=True)
out = []
imgs = set()
for p in papers:
    for e in p["exercises"]:
        assert e["verified"] and e["solution_complete"], e["id"]
        x = {k: e[k] for k in ("id", "type", "section", "instructions", "solution", "notes", "uncertain", "pages", "topic") if k in e}
        x["paper"] = p["id"]
        x["paper_notes"] = p.get("paper_notes", [])
        x["key_page"] = p["answer_key_page"]
        x["duplicate_of"] = dupof.get(e["id"])
        for k in ("headings", "texts", "title", "subtitle", "text", "questions", "situations", "ads", "gaps", "words", "no_solution_reason"):
            if k in e: x[k] = e[k]
        if e["type"] == "lesen3":
            pg = e["ads_image_page"]; x["ads_image"] = f"img/p{pg:03d}.jpg"; imgs.add(pg)
            x["ads"] = [dict(a, style=dict(style_for(pg, a["key"], a["text"]), icon=icon_for(p["id"], a["key"]))) for a in e["ads"]]
            if pg not in x["pages"]: x["pages"] = sorted(set(x["pages"]) | {pg})
        out.append(x)
# ---- Hörverstehen (extraction/hoeren, built by tools/hoeren.py) ----
import re
def join_instr(t):
    out = []
    for l in t.split("\n"):
        if out and not re.search(r'[.!?:]$', out[-1]):
            out[-1] += " " + l
        else:
            out.append(l)
    return "\n".join(out)
seen = {}
hv = {}
for f in sorted(glob.glob("extraction/hoeren/P??.json")):
    for e in json.load(open(f)):
        assert e["solution_complete"], e["id"]
        sts = [{"num": x["num"], "text": re.sub(r"\s{2,}", " ", x["text"]).strip()} for x in e["statements"]]
        key = (e["part"], tuple(re.sub(r"\W", "", x["text"].lower()) for x in sts), tuple(sorted(e["solution"].items())))
        x = {"id": e["id"], "type": "hoeren%d" % e["part"], "section": e["section"], "instructions": join_instr(e["instructions"]),
             "statements": sts, "solution": e["solution"], "notes": e["notes"], "uncertain": e["uncertain"], "pages": e["pages"],
             "topic": e["topic"], "paper": e["id"][:3], "paper_notes": [], "key_page": e["answer_key_page"],
             "duplicate_of": seen.get(key), "audio": False}
        seen.setdefault(key, e["id"])
        hv.setdefault(x["paper"], []).append(x)
merged = []
for pid in sorted({x["paper"] for x in out} | set(hv)):
    merged += [x for x in out if x["paper"] == pid] + hv.get(pid, [])
out = merged
for pg in sorted(imgs):
    f = f"website/img/p{pg:03d}.jpg"
    if not os.path.exists(f):
        d[pg - 1].get_pixmap(dpi=150).save(f, jpg_quality=82)
js = "/* Generated by tools/export_web.py from extraction/papers — do not edit by hand. */\nwindow.EXAM_DATA = " + json.dumps({"exercises": out}, ensure_ascii=False) + ";\n"
open("website/data/exercises.js", "w").write(js)
print(sum(1 for x in out if not x["type"].startswith("hoeren")), "L/SB +", sum(1 for x in out if x["type"].startswith("hoeren")), "HV =", len(out), "exercises;", len([x for x in out if not x["duplicate_of"]]), "unique;", len(imgs), "images;", round(len(js)/1024), "KB")
